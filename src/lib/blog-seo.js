function shorten(text, maximum) {
  if (text.length <= maximum) return text;
  const prefix = text.slice(0, maximum - 1);
  return `${prefix.slice(0, prefix.lastIndexOf(" ") || prefix.length).trimEnd()}…`;
}

export function getBlogSeo(post) {
  if (articleMetadata[post.slug]) return articleMetadata[post.slug];

  // New CMS articles retain their own subject; editorial overrides can be added above.
  const sourceTitle = String(post.title || "Apparel Sourcing Guide").replace(/\s+/g, " ").trim();
  const title = sourceTitle.length >= 50
    ? shorten(sourceTitle, 60)
    : shorten(`${sourceTitle} | OSD Apparels Manufacturing Blog`, 60);
  const excerpt = String(post.excerpt || post.content?.[0] || sourceTitle).replace(/\s+/g, " ").trim();
  const description = shorten(
    excerpt.length >= 140
      ? excerpt
      : `${excerpt} Read OSD Apparels insights for brands exploring garment sourcing, private label development, and clothing production in Pakistan.`,
    160,
  );

  return { title, description };
}

export function toIsoDate(value) {
  if (!value) return undefined;
  const date = new Date(value);
  return Number.isNaN(date.getTime()) ? undefined : date.toISOString();
}
