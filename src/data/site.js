function createShowcaseProducts(group, family) {
  return group.flatMap((category, index) =>
    [1, 2, 3].map((item) => ({
      slug: `${family}-${category.slug}-${item}`,
      family,
      category: category.slug,
      title: `${category.title} ${item}`,
      subtitle: `${category.fabrics[0]} • MOQ 30 pcs/style`,
      tone: index % 3,
      description: category.description,
      fabrics: category.fabrics,
    })),
  );
}

